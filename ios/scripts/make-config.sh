#!/bin/bash
# Write ios/Config.xcconfig (gitignored) from the repo .env: only SUPABASE_URL, SUPABASE_ANON_KEY and CART_ID.
# The anon key is public by design; the service-role key never goes near the app.
set -euo pipefail
cd "$(dirname "$0")/.."
ENV_FILE="${1:-../.env}"
value() { grep -E "^$1=" "$ENV_FILE" | tail -1 | cut -d= -f2- | sed -e 's/^"//' -e 's/"$//'; }
URL=$(value SUPABASE_URL)
KEY=$(value SUPABASE_ANON_KEY)
CART=$(value CART_ID)
{
  echo "// Generated by scripts/make-config.sh from $ENV_FILE. Do not commit."
  echo "SUPABASE_URL = $(printf '%s' "$URL" | sed 's#//#/$()/#')"   # xcconfig treats // as a comment
  echo "SUPABASE_ANON_KEY = $KEY"
  echo "CART_ID = ${CART:-7}"
} > Config.xcconfig
echo "wrote ios/Config.xcconfig (url ${URL:-unset}, cart ${CART:-7})"
