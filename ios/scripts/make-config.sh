#!/bin/bash
# Write ios/Config.xcconfig (gitignored) from the repo .env: only SUPABASE_URL, SUPABASE_ANON_KEY and CART_ID,
# plus your signing team.
# The anon key is public by design; the service-role key never goes near the app.
set -euo pipefail
cd "$(dirname "$0")/.."
ENV_FILE="${1:-../.env}"
value() { grep -E "^$1=" "$ENV_FILE" | tail -1 | cut -d= -f2- | sed -e 's/^"//' -e 's/"$//'; }
URL=$(value SUPABASE_URL)
KEY=$(value SUPABASE_ANON_KEY)
CART=$(value CART_ID)
# Signing for a real iPad: the team of the first "Apple Development" certificate in the keychain, so it
# survives `xcodegen generate`. Override with KART_TEAM_ID in .env.
TEAM=$(value KART_TEAM_ID || true)
if [ -z "$TEAM" ]; then
  TEAM=$(security find-certificate -c "Apple Development" -p 2>/dev/null \
    | openssl x509 -noout -subject 2>/dev/null | sed -n 's/.*OU *= *\([A-Z0-9]*\).*/\1/p' || true)
fi
{
  echo "// Generated by scripts/make-config.sh from $ENV_FILE. Do not commit."
  echo "SUPABASE_URL = $(printf '%s' "$URL" | sed 's#//#/$()/#')"   # xcconfig treats // as a comment
  echo "SUPABASE_ANON_KEY = $KEY"
  echo "CART_ID = ${CART:-7}"
  if [ -n "$TEAM" ]; then
    echo "DEVELOPMENT_TEAM = $TEAM"
    # Apple already has com.kart.app on another team: device builds get a per-team id; the simulator keeps com.kart.app.
    echo "KART_BUNDLE_SUFFIX[sdk=iphoneos*] = .$(printf '%s' "$TEAM" | tr '[:upper:]' '[:lower:]')"
  fi
} > Config.xcconfig
echo "wrote ios/Config.xcconfig (url ${URL:-unset}, cart ${CART:-7}, team ${TEAM:-none})"
